#!/usr/bin/env python3
"""Regenerate database/schema.sql and database/seed.sql from Flyway + the demo seed.

Flyway (src/main/resources/db/migration) stays the source of truth: the app builds its own schema.
These files are for reading, hand-in, or loading the demo menu into a database by hand.

What it does (Docker container mos_management_db, nothing on the host):
  1. creates a throwaway database, starts the packaged jar once against it with --mos.demo.seed=true
     (random one-off passwords, never printed or saved), waits for health, stops it;
  2. pg_dump: schema (no Flyway history table) and menu/store data as plain INSERTs.
     User accounts are left out on purpose: no password hashes in the repository;
  3. imports both files into a second throwaway database as a non-superuser to prove they load;
  4. drops both throwaway databases and the role.

Usage (from the repository root, after ./mvnw package):  python3 scripts/export-sql.py
"""
import os
import re
import secrets
import signal
import socket
import subprocess
import sys
import time
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
CONTAINER = os.environ.get('MOS_DB_CONTAINER', 'mos_management_db')
JAR = ROOT / 'target/dashboard-0.0.1-SNAPSHOT.jar'
OUT = ROOT / 'database'
DATA_TABLES = ['categories', 'products', 'option_groups', 'options', 'product_option_groups',
               'product_options', 'store_settings', 'opening_hours']
PORTABLE = re.compile(r'^(\\restrict |\\unrestrict |SET transaction_timeout)')


def psql(db, sql, user='mos'):
    return subprocess.run(['docker', 'exec', '-i', CONTAINER, 'psql', '-v', 'ON_ERROR_STOP=1', '-q', '-tA',
                           '-U', user, '-d', db], input=sql, text=True, capture_output=True, check=True).stdout


def dump(db, *args):
    out = subprocess.run(['docker', 'exec', CONTAINER, 'pg_dump', '-U', 'mos', '-d', db,
                          '--no-owner', '--no-privileges', *args], text=True, capture_output=True, check=True).stdout
    return ''.join(l for l in out.splitlines(keepends=True) if not PORTABLE.match(l))


def env_value(name):
    env_file = ROOT / '.env'
    if name in os.environ:
        return os.environ[name]
    for line in env_file.read_text().splitlines() if env_file.exists() else []:
        if line.startswith(name + '='):
            return line.split('=', 1)[1].strip()
    sys.exit(f'{name} is not set (environment or .env)')


def free_port():
    with socket.socket() as s:
        s.bind(('127.0.0.1', 0))
        return s.getsockname()[1]


def main():
    if not JAR.exists():
        sys.exit('Build first: ./mvnw package')
    tag = secrets.token_hex(3)
    src, check, role = f'mos_export_{tag}', f'mos_import_check_{tag}', f'mos_import_check_{tag}'
    subprocess.run(['docker', 'exec', CONTAINER, 'createdb', '-U', 'mos', src], check=True)
    server = None
    try:
        port = free_port()
        env = {**os.environ,
               'MOS_DB_URL': f'jdbc:postgresql://127.0.0.1:54322/{src}',
               'MOS_DB_USER': env_value('MOS_DB_USER'), 'MOS_DB_PASSWORD': env_value('MOS_DB_PASSWORD'),
               'MOS_JWT_SECRET': secrets.token_urlsafe(48),
               'MOS_DEMO_ADMIN_PASSWORD': secrets.token_urlsafe(18),
               'MOS_DEMO_STAFF_PASSWORD': secrets.token_urlsafe(18)}
        server = subprocess.Popen(['java', '-jar', str(JAR), f'--server.port={port}', '--server.address=127.0.0.1',
                                   '--mos.demo.seed=true'], cwd=ROOT, env=env,
                                  stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for _ in range(90):
            try:
                urlopen(f'http://127.0.0.1:{port}/actuator/health', timeout=2)
                break
            except OSError:
                if server.poll() is not None:
                    sys.exit('The app stopped while seeding; run it by hand to see why.')
                time.sleep(1)
        else:
            sys.exit('The app did not become healthy in 90 s.')
        server.send_signal(signal.SIGTERM)
        server.wait(30)
        server = None

        header = ('-- MOS (Mobile Ordering System) — {what}\n'
                  '-- Generated by scripts/export-sql.py from Flyway V1 and the demo seed. Do not edit by hand.\n'
                  '-- PostgreSQL 13+. The app itself builds this schema with Flyway; use these files to read,\n'
                  '-- hand in, or load a database by hand (schema.sql first, then seed.sql).\n\n')
        schema = header.format(what='schema (14 tables)') + dump(src, '--schema-only', '-T', 'flyway_schema_history')
        data_args = ['--data-only', '--column-inserts'] + [a for t in DATA_TABLES for a in ('-t', t)]
        seed = (header.format(what='seed data: demo menu, options, store settings and hours (no user accounts)')
                + 'BEGIN;\n' + dump(src, *data_args) + 'COMMIT;\n')
        OUT.mkdir(exist_ok=True)
        schema, seed = schema.rstrip('\n') + '\n', seed.rstrip('\n') + '\n'
        (OUT / 'schema.sql').write_text(schema)
        (OUT / 'seed.sql').write_text(seed)

        # Prove both files load as an ordinary (non-superuser) role into an empty database.
        psql('postgres', f"CREATE ROLE {role} LOGIN; CREATE DATABASE {check} OWNER {role};")
        psql(check, schema, user=role)
        psql(check, seed, user=role)
        counts = psql(check, 'SELECT ' + ', '.join(f"(SELECT count(*) FROM {t})" for t in DATA_TABLES) + ';')
        users = psql(check, 'SELECT count(*) FROM users;').strip()
        print('Imported as non-superuser:', dict(zip(DATA_TABLES, counts.split('|'))) if '|' in counts else counts.strip(),
              '| users:', users)
        print(f'Wrote {OUT / "schema.sql"} and {OUT / "seed.sql"}')
    finally:
        if server is not None:
            server.kill()
        subprocess.run(['docker', 'exec', CONTAINER, 'dropdb', '-U', 'mos', '--if-exists', src], check=False)
        subprocess.run(['docker', 'exec', CONTAINER, 'dropdb', '-U', 'mos', '--if-exists', check], check=False)
        subprocess.run(['docker', 'exec', CONTAINER, 'psql', '-q', '-U', 'mos', '-d', 'postgres', '-c',
                        f'DROP ROLE IF EXISTS {role}'], check=False, capture_output=True)


if __name__ == '__main__':
    main()
